export type AuthoritativeOutcome =
  | 'NO_CONFIRMED_BUG'
  | 'BUG_CONFIRMED_BUT_PROPOSAL_FAILED'
  | 'FIXED_AND_VERIFIED'
  | 'AWAITING_APPROVAL'
  | 'FAILED'
  | 'REJECTED'
  | 'ACTIVE'
  | 'CREATED';

export interface TaskOutcomeDetails {
  outcome: AuthoritativeOutcome;
  isNoConfirmedBug: boolean;
  isFixedAndVerified: boolean;
  isFailed: boolean;
  isAwaitingApproval: boolean;
  isRejected: boolean;
  isActive: boolean;
  isCreated: boolean;
  shouldShowDiagnosis: boolean;
  shouldShowProposedChange: boolean;
  shouldShowVerificationSteps: boolean;
  shouldShowSummary: boolean;
  shouldShowGitBranch: boolean;
  explanation: string;
  filesModifiedCount: number;
  patchesGeneratedCount: number;
  approvalsRequestedCount: number;
}

/**
 * Resolves the single source-of-truth authoritative outcome of a task.
 *
 * Precedence Rule:
 * If the authoritative persisted outcome is NO_CONFIRMED_BUG (via status,
 * root_cause.outcome, or authoritative summary prefix), it MUST WIN over any
 * contradictory text generated by LLM reasoning turns. Speculative root-cause
 * diagnoses, proposed code changes, "bug fixed" statements, and fabricated
 * verification steps are strictly suppressed.
 */
export function resolveAuthoritativeOutcome(
  task: {
    status?: string;
    type?: string;
    summary?: string | null;
    root_cause?: { outcome?: string; evidence?: string; analysis?: string | null; [key: string]: any } | null;
    error?: { reason?: string; exception?: string; [key: string]: any } | null;
    error_message?: string;
  },
  changes: Array<{ id: string; status?: string; [key: string]: any }> = [],
  gitInfo?: { branch?: string; suggested_commit?: string; [key: string]: any } | null
): TaskOutcomeDetails {
  const statusUpper = (task.status || '').toUpperCase();
  const summaryStr = String(task.summary || '');
  const rootCauseOutcome = task.root_cause?.outcome;

  // 1. Authoritative NO_CONFIRMED_BUG
  const isExplicitNoBug =
    statusUpper === 'NO_CONFIRMED_BUG' ||
    rootCauseOutcome === 'NO_CONFIRMED_BUG' ||
    summaryStr.startsWith('NO_CONFIRMED_BUG') ||
    (statusUpper === 'COMPLETED' &&
      changes.length === 0 &&
      !gitInfo?.branch &&
      (summaryStr.includes('No reproducible defect') || summaryStr.includes('NO_CONFIRMED_BUG')));

  if (isExplicitNoBug) {
    return {
      outcome: 'NO_CONFIRMED_BUG',
      isNoConfirmedBug: true,
      isFixedAndVerified: false,
      isFailed: false,
      isAwaitingApproval: false,
      isRejected: false,
      isActive: false,
      isCreated: false,
      shouldShowDiagnosis: false, // Never show diagnosis of a bug when no bug was confirmed
      shouldShowProposedChange: false, // Never show proposed code change
      shouldShowVerificationSteps: false, // Never show fabricated verification steps
      shouldShowSummary: true,
      shouldShowGitBranch: false,
      explanation:
        'DevAgent thoroughly examined the repository and determined that no reproducible software defect exists based on repository evidence.',
      filesModifiedCount: 0,
      patchesGeneratedCount: 0,
      approvalsRequestedCount: 0,
    };
  }

  // 1b. BUG_CONFIRMED_BUT_PROPOSAL_FAILED
  const isProposalFailed =
    statusUpper === 'BUG_CONFIRMED_BUT_PROPOSAL_FAILED' ||
    rootCauseOutcome === 'BUG_CONFIRMED_BUT_PROPOSAL_FAILED' ||
    summaryStr.startsWith('BUG_CONFIRMED_BUT_PROPOSAL_FAILED');

  if (isProposalFailed) {
    return {
      outcome: 'BUG_CONFIRMED_BUT_PROPOSAL_FAILED',
      isNoConfirmedBug: false,
      isFixedAndVerified: false,
      isFailed: true,
      isAwaitingApproval: false,
      isRejected: false,
      isActive: false,
      isCreated: false,
      shouldShowDiagnosis: false,
      shouldShowProposedChange: false,
      shouldShowVerificationSteps: false,
      shouldShowSummary: true,
      shouldShowGitBranch: false,
      explanation: String(
        task.error?.reason ||
          task.summary ||
          'Defect confirmed from repository evidence, but structured proposal generation failed.'
      ),
      filesModifiedCount: 0,
      patchesGeneratedCount: 0,
      approvalsRequestedCount: 0,
    };
  }

  // 2. FAILED
  if (
    statusUpper === 'FAILED' ||
    (task.error && Object.keys(task.error).length > 0 && statusUpper !== 'COMPLETED')
  ) {
    return {
      outcome: 'FAILED',
      isNoConfirmedBug: false,
      isFixedAndVerified: false,
      isFailed: true,
      isAwaitingApproval: false,
      isRejected: false,
      isActive: false,
      isCreated: false,
      shouldShowDiagnosis: false, // Do not present generated text as a diagnosis of a successful fix
      shouldShowProposedChange: false,
      shouldShowVerificationSteps: false,
      shouldShowSummary: false,
      shouldShowGitBranch: false,
      explanation: String(
        task.error?.reason ||
          task.error?.exception ||
          task.error_message ||
          'Task execution encountered an error.'
      ),
      filesModifiedCount: 0,
      patchesGeneratedCount: changes.length,
      approvalsRequestedCount: 0,
    };
  }

  // 3. REJECTED
  if (statusUpper === 'REJECTED') {
    return {
      outcome: 'REJECTED',
      isNoConfirmedBug: false,
      isFixedAndVerified: false,
      isFailed: false,
      isAwaitingApproval: false,
      isRejected: true,
      isActive: false,
      isCreated: false,
      shouldShowDiagnosis: false,
      shouldShowProposedChange: true, // Let user inspect what was rejected
      shouldShowVerificationSteps: false,
      shouldShowSummary: false,
      shouldShowGitBranch: false,
      explanation: 'The proposed changes were reviewed and rejected. No modifications were applied.',
      filesModifiedCount: 0,
      patchesGeneratedCount: changes.length,
      approvalsRequestedCount: 1,
    };
  }

  // 4. AWAITING_APPROVAL / FIX_PROPOSED
  if (statusUpper === 'AWAITING_APPROVAL' || statusUpper === 'FIX_PROPOSED') {
    return {
      outcome: 'AWAITING_APPROVAL',
      isNoConfirmedBug: false,
      isFixedAndVerified: false,
      isFailed: false,
      isAwaitingApproval: true,
      isRejected: false,
      isActive: false,
      isCreated: false,
      shouldShowDiagnosis: true,
      shouldShowProposedChange: true,
      shouldShowVerificationSteps: false,
      shouldShowSummary: false,
      shouldShowGitBranch: false,
      explanation: 'Human-in-the-loop approval is required to apply the proposed patch.',
      filesModifiedCount: 0,
      patchesGeneratedCount: changes.length,
      approvalsRequestedCount: 1,
    };
  }

  // 5. Genuine FIXED_AND_VERIFIED
  if (statusUpper === 'COMPLETED') {
    const hasVerifiedArtifacts =
      summaryStr.startsWith('FIXED_AND_VERIFIED') ||
      Boolean(gitInfo?.branch) ||
      changes.some((c) => c.status === 'APPLIED' || c.status === 'applied');

    if (hasVerifiedArtifacts) {
      return {
        outcome: 'FIXED_AND_VERIFIED',
        isNoConfirmedBug: false,
        isFixedAndVerified: true,
        isFailed: false,
        isAwaitingApproval: false,
        isRejected: false,
        isActive: false,
        isCreated: false,
        shouldShowDiagnosis: Boolean(task.root_cause?.analysis),
        shouldShowProposedChange: true,
        shouldShowVerificationSteps: true,
        shouldShowSummary: true,
        shouldShowGitBranch: Boolean(gitInfo?.branch),
        explanation: summaryStr || 'Fix applied and verified successfully in sandbox.',
        filesModifiedCount: changes.length,
        patchesGeneratedCount: changes.length,
        approvalsRequestedCount: 1,
      };
    }

    // Non-bug tasks (e.g. questions, documentation)
    if (task.type === 'question' || task.type === 'documentation' || task.type === 'docs') {
      return {
        outcome: 'FIXED_AND_VERIFIED',
        isNoConfirmedBug: false,
        isFixedAndVerified: true,
        isFailed: false,
        isAwaitingApproval: false,
        isRejected: false,
        isActive: false,
        isCreated: false,
        shouldShowDiagnosis: false,
        shouldShowProposedChange: false,
        shouldShowVerificationSteps: false,
        shouldShowSummary: true,
        shouldShowGitBranch: false,
        explanation: summaryStr || 'Task completed successfully.',
        filesModifiedCount: 0,
        patchesGeneratedCount: 0,
        approvalsRequestedCount: 0,
      };
    }

    // Fallback: If completed but no artifacts exist for bug_fix, it is NO_CONFIRMED_BUG
    return {
      outcome: 'NO_CONFIRMED_BUG',
      isNoConfirmedBug: true,
      isFixedAndVerified: false,
      isFailed: false,
      isAwaitingApproval: false,
      isRejected: false,
      isActive: false,
      isCreated: false,
      shouldShowDiagnosis: false,
      shouldShowProposedChange: false,
      shouldShowVerificationSteps: false,
      shouldShowSummary: true,
      shouldShowGitBranch: false,
      explanation:
        'DevAgent thoroughly examined the repository and determined that no reproducible software defect exists based on repository evidence.',
      filesModifiedCount: 0,
      patchesGeneratedCount: 0,
      approvalsRequestedCount: 0,
    };
  }

  // 6. Active / Created
  const isActive = ['PLANNING', 'ANALYZING', 'INVESTIGATING', 'APPLYING', 'TESTING'].includes(statusUpper);
  return {
    outcome: isActive ? 'ACTIVE' : 'CREATED',
    isNoConfirmedBug: false,
    isFixedAndVerified: false,
    isFailed: false,
    isAwaitingApproval: false,
    isRejected: false,
    isActive,
    isCreated: !isActive,
    shouldShowDiagnosis: false,
    shouldShowProposedChange: false,
    shouldShowVerificationSteps: false,
    shouldShowSummary: false,
    shouldShowGitBranch: false,
    explanation: isActive ? 'Task execution is currently in progress.' : 'Task is created and queued.',
    filesModifiedCount: 0,
    patchesGeneratedCount: 0,
    approvalsRequestedCount: 0,
  };
}
